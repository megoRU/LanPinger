import fs from "node:fs";

const config = JSON.parse(fs.readFileSync(new URL("../src-tauri/tauri.conf.json", import.meta.url), "utf8"));
const key = config.plugins?.updater?.pubkey;
const endpoint = config.plugins?.updater?.endpoints?.[0];
const updater = config.plugins?.updater;
if (!key || key.includes("REPLACE_WITH") || key.length < 80) {
  console.error("Set plugins.updater.pubkey to the public key generated by `npx tauri signer generate` before creating a signed release.");
  process.exit(1);
}
if (endpoint !== "https://github.com/megoRU/LanPinger/releases/latest/download/latest.json") {
  console.error("Updater endpoint must point to the LanPinger stable latest.json release asset.");
  process.exit(1);
}
if (updater.requireSignedVersion !== true || updater.allowDowngrades !== false) {
  console.error("Updater must require signed versions and reject downgrades.");
  process.exit(1);
}
if (!process.env.TAURI_SIGNING_PRIVATE_KEY) {
  console.error("TAURI_SIGNING_PRIVATE_KEY is missing. Add it as a GitHub Actions secret before releasing.");
  process.exit(1);
}
if (process.env.TAURI_SIGNING_PRIVATE_KEY_PASSWORD === undefined) {
  console.error("TAURI_SIGNING_PRIVATE_KEY_PASSWORD is missing. Use an empty secret for an unencrypted key.");
  process.exit(1);
}
console.log("Updater public key and signing secrets are configured.");
